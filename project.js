/* =========================
   GET PROJECT
========================= */

let urlParams =
    new URLSearchParams(window.location.search);

let projectId =
    urlParams.get("id");

let project =
    projects[projectId];


if (!project) {

    window.location.href = "projects.html";

} else {

    document.title =
        project.title + " — Aymane Boutahar";


    /* =========================
       HERO
    ========================== */

    document.getElementById("project-number").textContent =
        project.number + " — PROJECT";

    document.getElementById("project-title").innerHTML =
        project.title +
        "<br><span>" +
        project.titleSecond +
        "</span>";

    document.getElementById("project-intro").textContent =
        project.intro;


    /* =========================
       META
    ========================== */

    document.getElementById("project-type").textContent =
        project.type;

    document.getElementById("project-tools").textContent =
        project.tools;

    document.getElementById("project-year").textContent =
        project.year;




    /* =========================
       DESCRIPTION
    ========================== */

    document.getElementById("project-description").textContent =
        project.description;

    document.getElementById("project-description-2").textContent =
        project.description2;


    /* =========================
       ABOUT IMAGE / VIDEO
    ========================== */

    let aboutImage =
        document.getElementById("project-image1");

    let aboutVideoContainer =
        document.getElementById("about-video-container");

    let aboutVideo =
        document.getElementById("about-project-video");


    if (project.image1) {

        aboutImage.style.display = "block";

        aboutImage.src =
            project.image1;

        aboutVideoContainer.style.display =
            "none";

    } else if (project.aboutVideo) {

        aboutImage.style.display =
            "none";

        aboutVideoContainer.style.display =
            "block";

        aboutVideo.src =
            "https://www.youtube.com/embed/" +
            project.aboutVideo;

    } else {

        aboutImage.style.display =
            "none";

        aboutVideoContainer.style.display =
            "none";

    }


    /* =========================
       PROCESS
    ========================== */

    document.getElementById("project-research").textContent =
        project.research;

    document.getElementById("project-development").textContent =
        project.development;

    document.getElementById("project-result").textContent =
        project.result;


    /* =========================
       GALLERY
    ========================== */

    let galleryTrack =
        document.getElementById("gallery-track");

    galleryTrack.innerHTML = "";


    /* CREATE GALLERY IMAGES */

    for (let i = 0; i < project.gallery.length; i++) {

        let image =
            document.createElement("img");

        image.src =
            project.gallery[i];

        image.alt =
            project.title +
            " gallery image";

        image.classList.add("gallery-image");

        image.dataset.index =
            i;

        galleryTrack.appendChild(image);

    }


    let galleryImages =
        document.querySelectorAll(".gallery-image");


    /* =========================
       GALLERY CONTROLS
    ========================== */

    let galleryPrev =
        document.getElementById("gallery-prev");

    let galleryNext =
        document.getElementById("gallery-next");

    let currentGalleryImage =
        0;


    /* NEXT */

    galleryNext.addEventListener("click", function() {

        currentGalleryImage++;

        if (
            currentGalleryImage >=
            galleryImages.length
        ) {

            currentGalleryImage = 0;

        }

        galleryImages[currentGalleryImage].scrollIntoView({
            behavior: "smooth",
            block: "nearest",
            inline: "center"
        });

    });


    /* PREVIOUS */

    galleryPrev.addEventListener("click", function() {

        currentGalleryImage--;

        if (currentGalleryImage < 0) {

            currentGalleryImage =
                galleryImages.length - 1;

        }

        galleryImages[currentGalleryImage].scrollIntoView({
            behavior: "smooth",
            block: "nearest",
            inline: "center"
        });

    });


    /* =========================
       LIGHTBOX
    ========================== */

    let lightbox =
        document.getElementById("image-lightbox");

    let lightboxImage =
        document.getElementById("lightbox-image");

    let lightboxClose =
        document.getElementById("lightbox-close");

    let lightboxPrev =
        document.getElementById("lightbox-prev");

    let lightboxNext =
        document.getElementById("lightbox-next");

    let currentImage =
        0;


    /* SHOW IMAGE */

    function showLightboxImage(index) {

        currentImage =
            index;

        lightboxImage.src =
            project.gallery[currentImage];

        lightbox.classList.add("active");

        document.body.style.overflow =
            "hidden";

    }


    /* CLOSE */

    function closeLightbox() {

        lightbox.classList.remove("active");

        document.body.style.overflow =
            "";

    }


    /* NEXT */

    function nextLightboxImage() {

        currentImage++;

        if (
            currentImage >=
            project.gallery.length
        ) {

            currentImage = 0;

        }

        lightboxImage.src =
            project.gallery[currentImage];

    }


    /* PREVIOUS */

    function previousLightboxImage() {

        currentImage--;

        if (currentImage < 0) {

            currentImage =
                project.gallery.length - 1;

        }

        lightboxImage.src =
            project.gallery[currentImage];

    }


    /* CLICK GALLERY IMAGE */

    galleryImages.forEach(function(image) {

        image.addEventListener("click", function() {

            let index =
                Number(image.dataset.index);

            showLightboxImage(index);

        });

    });


    /* LIGHTBOX BUTTONS */

    lightboxClose.addEventListener(
        "click",
        closeLightbox
    );

    lightboxNext.addEventListener(
        "click",
        nextLightboxImage
    );

    lightboxPrev.addEventListener(
        "click",
        previousLightboxImage
    );


    /* CLICK BACKGROUND */

    lightbox.addEventListener("click", function(event) {

        if (event.target === lightbox) {

            closeLightbox();

        }

    });


    /* KEYBOARD */

    document.addEventListener("keydown", function(event) {

        if (!lightbox.classList.contains("active")) {

            return;

        }

        if (event.key === "Escape") {

            closeLightbox();

        }

        if (event.key === "ArrowRight") {

            nextLightboxImage();

        }

        if (event.key === "ArrowLeft") {

            previousLightboxImage();

        }

    });


    /* =========================
       REFLECTION
    ========================== */

    document.getElementById("project-reflection").textContent =
        project.reflection;


    /* =========================
       PROJECT VIDEO
    ========================== */

    let videoSection =
        document.getElementById("project-video-section");

    let video =
        document.getElementById("project-video");


    if (project.video) {

        videoSection.style.display =
            "block";

        video.src =
            "https://www.youtube.com/embed/" +
            project.video;

    } else {

        videoSection.style.display =
            "none";

    }

}
